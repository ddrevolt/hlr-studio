#!/usr/bin/env python3
"""Copy the page's data into app/src/data/ and write assets.ts: the type specimens and the
PNG-only marks as data URIs, and the two vector marks as inline SVG whose fill follows the ink
(logo-assets.md rule 2: a mark's fill binds to the ink; the file's own fill is ignored).
Usage: python3 gen_assets.py"""
import base64, json, os, re, shutil

here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, "app", "src", "data")
os.makedirs(dst, exist_ok=True)
for f in ("content.json", "review-data.json"):
    shutil.copyfile(os.path.join(here, f), os.path.join(dst, f))
A = os.path.join(here, "assets")
M = json.load(open(os.path.join(A, "manifest.json"), encoding="utf-8"))
shutil.copyfile(os.path.join(A, "manifest.json"), os.path.join(dst, "manifest.json"))


def uri(p):
    return "data:image/png;base64," + base64.b64encode(open(p, "rb").read()).decode("ascii")


def svg(p):
    s = open(p, encoding="utf-8").read()
    s = re.sub(r"<\?xml[^>]*\?>", "", s)
    s = re.sub(r"<defs>.*?</defs>", "", s, flags=re.S)
    s = s.replace(' class="cls-1"', "")
    s = re.sub(r'<svg[^>]*?viewBox="([^"]+)"[^>]*>', r'<svg xmlns="http://www.w3.org/2000/svg" viewBox="\1" fill="currentColor" aria-hidden="true">', s, count=1)
    return re.sub(r"\s+", " ", s).strip()


out = {"specimens": {}, "marks": {}}
for s in M["specimens"]:
    out["specimens"][s["style"]] = {"src": uri(os.path.join(A, s["file"])), "w": s["width"], "h": s["height"], "text": s["text"], "px": s["web_px"]}
for m in M["marks"]:
    p = os.path.join(A, m["file"])
    if m["file"].endswith(".svg"):
        out["marks"][m["file"]] = {"svg": svg(p)}
    else:
        w, h = m.get("size", [0, 0])
        out["marks"][m["file"]] = {"src": uri(p), "w": w, "h": h}
ts = "/* Generated by gen_assets.py from assets/ (rendered from HLR's own files by tools/render_assets.py). Do not hand-edit. */\n"
ts += "export const assets: { specimens: Record<string, { src: string; w: number; h: number; text: string; px: number }>; marks: Record<string, { svg?: string; src?: string; w?: number; h?: number }> } = "
ts += json.dumps(out) + "\n"
open(os.path.join(dst, "assets.ts"), "w", encoding="utf-8").write(ts)
print(f"wrote {dst}: {len(out['specimens'])} specimens, {len(out['marks'])} marks, assets.ts {os.path.getsize(os.path.join(dst, 'assets.ts'))} bytes")
