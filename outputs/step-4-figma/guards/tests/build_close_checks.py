#!/usr/bin/env python3
"""Builds guards/close_checks.js from the page guards (Chat 6, 2026-10-23, after the batch 2 review round 2, BR2-07:
the second sighting of a guard not rerun on a page whose masters changed). close_checks.js runs the page guards on
the library pages in one read-only use_figma call, so a close cannot skip a page: entity_scan.js on 00 to 04,
r8_text_nodes.js on 01 to 04, structure_lint.js on 01 and 02 (with the set counts slotmap.yaml holds as its floor),
email_ground.js on 02 to 04 and host_placeholders.js on 02. Each guard's body is copied verbatim into a function;
only its header comment and its PAGE, SETS and CLOSED lines are left out (they become arguments, and CLOSED is pasted
once at the top). board_drift.js stays its own run (00 Foundations, with board_expect.py's EXPECT).
Usage: python3 build_close_checks.py <brand home> [--check]. With --check it rebuilds in memory and exits 1 when the
file on disk differs (a guard or the slot map changed and close_checks.js was not rebuilt)."""
import os, re, sys
home = sys.argv[1]; check = '--check' in sys.argv
G = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
GUARDS = [('entity', 'entity_scan.js'), ('r8', 'r8_text_nodes.js'), ('lint', 'structure_lint.js'),
          ('ground', 'email_ground.js'), ('placeholders', 'host_placeholders.js')]
RUNS = [('0:1', ['entity']), ('7:2', ['r8', 'entity', 'lint']), ('7:3', ['r8', 'entity', 'lint', 'ground', 'placeholders']),
        ('7:4', ['r8', 'entity', 'ground']), ('7:5', ['r8', 'entity', 'ground'])]
sm = open(os.path.join(home, 'brand-pack', 'slotmap.yaml'), encoding='utf-8').read()
sets = {'7:2': len(re.findall(r'^  E\d\d:\s*$', sm, re.M)), '7:3': len(re.findall(r'^  M\d\d:\s*$', sm, re.M))}
def body(fn):
    lines = open(os.path.join(G, fn), encoding='utf-8').read().rstrip('\n').split('\n')
    while lines and lines[0].startswith('//'): lines.pop(0)
    return '\n'.join(l for l in lines if not re.match(r'^const (PAGE|SETS|CLOSED) = .*;$', l))
out = ['// GENERATED by tests/build_close_checks.py from ' + ', '.join(f for _, f in GUARDS) + ' and slotmap.yaml; do not edit.',
       '// Read-only. Paste board_expect.py\'s "closed" list as CLOSED, then run with use_figma once at every close that builds',
       '// or changes a master, a board or a template: it runs the page guards on the library pages (board_drift.js runs on',
       '// its own, on 00 Foundations) and returns the failures.',
       'const CLOSED = PASTE_CLOSED_GATES_HERE;']
for name, fn in GUARDS:
    out += ['async function %s(PAGE, SETS) {' % name, body(fn), '}']
out += ['const G = { %s };' % ', '.join(n for n, _ in GUARDS),
        'const RUNS = [%s];' % ', '.join("['%s', [%s]]" % (p, ', '.join("'%s'" % g for g in gs)) for p, gs in RUNS),
        'const SETS = { %s };' % ', '.join("'%s': %d" % kv for kv in sets.items()),
        'const runs = []; let failing = 0;',
        'for (const [p, names] of RUNS) for (const g of names) {',
        '  const r = await G[g](p, SETS[p]); const bad = r.fails || r.hits || []; failing += bad.length;',
        '  runs.push({ page: p, guard: g, counts: Object.fromEntries(Object.entries(r).filter(([, v]) => typeof v === \'number\')), fails: bad.slice(0, 15) });',
        '}',
        'return { failing, runs };']
text = '\n'.join(out) + '\n'
dest = os.path.join(G, 'close_checks.js')
if check:
    same = os.path.exists(dest) and open(dest, encoding='utf-8').read() == text
    print('close_checks.js ' + ('current' if same else 'STALE: rebuild it with build_close_checks.py'))
    sys.exit(0 if same else 1)
open(dest, 'w', encoding='utf-8').write(text)
print('close_checks.js written: %d guards, %d runs, sets %s' % (len(GUARDS), sum(len(g) for _, g in RUNS), sets))
