#!/usr/bin/env python3
"""Write the explainer's theme.css from the pack's own web tokens (brand-pack/web/tokens.css).

The page uses HLR's exported custom properties as they are: the default block for the light
theme, the night ground for the dark theme, and the [data-ground] blocks for bands on the
deep and warm grounds. Page aliases are declared on :root and on every [data-ground] so they
re-resolve inside a band. shadcn's HSL channels are computed from the same values.

Usage: python3 gen_theme.py [--home <brand home>] --out <app>/src/theme.css
"""
import argparse, os, re, colorsys

here = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--home", default=os.path.normpath(os.path.join(here, "..", "..")))
ap.add_argument("--out", required=True)
a = ap.parse_args()

src = os.path.join(a.home, "brand-pack", "web", "tokens.css")
css = open(src, encoding="utf-8").read()


def block(selector):
    m = re.search(re.escape(selector) + r"\s*\{(.*?)\n\}", css, re.S)
    if not m:
        raise SystemExit(f"gen_theme.py: no {selector} block in {src}")
    return m.group(1)


def decls(body):
    return dict(re.findall(r"(--[\w-]+):\s*([^;]+);", body))


root = block(":root")
night = block('[data-ground="night"]')
rv, nv = decls(root), decls(night)
nightv = {**rv, **nv}


def hsl(hexv):
    h = hexv.strip().lstrip("#")[:6]
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    hh, ll, ss = colorsys.rgb_to_hls(r, g, b)
    return f"{hh * 360:.1f} {ss * 100:.1f}% {ll * 100:.1f}%"


def shad(v, line):
    bg = v["--hlr-color-semantic-background-default"]
    fg = v["--hlr-color-semantic-text-primary"]
    mu = v["--hlr-color-semantic-text-muted"]
    sb = v["--hlr-color-semantic-background-subtle"]
    return "\n".join([
        f"  --background: {hsl(bg)};", f"  --foreground: {hsl(fg)};",
        f"  --card: {hsl(bg)};", f"  --card-foreground: {hsl(fg)};",
        f"  --popover: {hsl(bg)};", f"  --popover-foreground: {hsl(fg)};",
        f"  --primary: {hsl(fg)};", f"  --primary-foreground: {hsl(bg)};",
        f"  --secondary: {hsl(sb)};", f"  --secondary-foreground: {hsl(fg)};",
        f"  --muted: {hsl(sb)};", f"  --muted-foreground: {hsl(mu)};",
        f"  --accent: {hsl(sb)};", f"  --accent-foreground: {hsl(fg)};",
        f"  --destructive: {hsl(fg)};", f"  --destructive-foreground: {hsl(bg)};",
        f"  --border: {hsl(line)};", f"  --input: {hsl(line)};", f"  --ring: {hsl(fg)};",
        "  --radius: 0px;",
    ])


aliases = """  --bg: var(--hlr-color-semantic-background-default);
  --fg: var(--hlr-color-semantic-text-primary);
  --ink-muted: var(--hlr-color-semantic-text-muted);
  --surface: var(--hlr-color-semantic-background-subtle);
  --rule: var(--hlr-component-rule-stroke);
  --paper: var(--hlr-color-extended-white);
  --placeholder: var(--hlr-component-placeholder-fill);"""

out = [
    "/* Generated by outputs/explainer/gen_theme.py from brand-pack/web/tokens.css. Do not hand-edit. */",
    "/* Light: HLR's default (light) ground. Dark: HLR's night ground. Bands use [data-ground]. */",
    ":root {" + root + "\n" + aliases + "\n  --line: var(--hlr-color-extended-neutral-200);\n" + shad(rv, rv["--hlr-color-extended-neutral-200"]) + "\n}",
]
for g in ("light", "warm", "deep", "night"):
    body = block(f'[data-ground="{g}"]')
    line = "var(--hlr-color-extended-neutral-200)" if g in ("light", "warm") else "var(--hlr-color-extended-neutral-800)"
    out.append(f'[data-ground="{g}"] {{' + body + "\n" + aliases + f"\n  --line: {line};\n  background: var(--bg);\n  color: var(--fg);\n}}")
dark_body = night + "\n" + aliases + "\n  --line: var(--hlr-color-extended-neutral-800);\n" + shad(nightv, rv["--hlr-color-extended-neutral-800"]) + "\n  color-scheme: dark;"
out.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {" + dark_body + "\n  }\n}")
out.append(':root[data-theme="dark"] {' + dark_body + "\n}")
os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
with open(a.out, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print(f"wrote {a.out} from {os.path.relpath(src, a.home)}")
