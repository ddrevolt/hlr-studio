#!/usr/bin/env python3
"""Copy the explainer's content, data and verdicts into app/src/data and write the email preview
module from the demo run's PNG (flattened on white, JPEG). Needs Pillow for the preview.
Usage: python3 gen_assets.py [--home <brand home>] [--preview <png relative to the brand home>]"""
import argparse, base64, io, os, shutil

here = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--home", default=os.path.normpath(os.path.join(here, "..", "..")))
ap.add_argument("--preview", default="outputs/step-4-figma/demo-email/demo-email-preview.png")
a = ap.parse_args()
dst = os.path.join(here, "app", "src", "data")
os.makedirs(dst, exist_ok=True)
for f in ("content.json", "explainer-data.json", "examples-verified.json"):
    shutil.copyfile(os.path.join(here, f), os.path.join(dst, f))
from PIL import Image
im = Image.open(os.path.join(a.home, a.preview)).convert("RGBA")
bg = Image.new("RGB", im.size, (255, 255, 255))
bg.paste(im, mask=im.split()[3])
buf = io.BytesIO()
bg.save(buf, "JPEG", quality=84, optimize=True, progressive=True)
b64 = base64.b64encode(buf.getvalue()).decode()
with open(os.path.join(dst, "preview.ts"), "w", encoding="utf-8") as f:
    f.write(f"// Generated by gen_assets.py from {a.preview}\n")
    f.write(f'export const previewSrc = "data:image/jpeg;base64,{b64}";\n')
    f.write(f"export const previewSize = {{ w: {im.size[0]}, h: {im.size[1]} }};\n")
print(f"copied 3 files to {dst}; preview {im.size[0]}x{im.size[1]}, {len(b64)} base64 chars")
