#!/usr/bin/env python3
"""Build explainer-data.json for the HLR forge explainer from the pack and the record.

Reads, never writes, the pack: every number on the page is counted here from the files
themselves, and every source file's sha256 goes into the stamp, so guards/explainer_drift.py
can tell when the page has fallen behind the pack.

Usage:
  python3 build_data.py [--home <brand home>] [--pack <pack folder>] [--out <file>] [--commit <sha>]

Defaults: --home is two folders up from this file (outputs/explainer/ sits in the brand home),
--pack is <home>/brand-pack, --out is explainer-data.json beside this file. --commit is only
for a copy without git; in the brand home the commit is read with git.

Needs Python 3.8+ and PyYAML (pip install pyyaml).
"""
import argparse, datetime, hashlib, json, os, re, subprocess, sys

try:
    import yaml
except ImportError:
    sys.exit("build_data.py needs PyYAML: pip install pyyaml")

EM_DASH = chr(0x2014)
DEMO = "outputs/step-4-figma/demo-email"
SLUG = "made-to-order-pendants"

ap = argparse.ArgumentParser()
here = os.path.dirname(os.path.abspath(__file__))
ap.add_argument("--home", default=os.path.normpath(os.path.join(here, "..", "..")))
ap.add_argument("--pack", default=None)
ap.add_argument("--out", default=os.path.join(here, "explainer-data.json"))
ap.add_argument("--commit", default=None)
args = ap.parse_args()
HOME = os.path.abspath(args.home)
PACK = os.path.abspath(args.pack or os.path.join(HOME, "brand-pack"))
PACK_REL = os.path.relpath(PACK, HOME)

used = {}  # relpath -> sha256


def rel(p):
    return os.path.relpath(p, HOME)


def read(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    used[rel(path)] = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return text


def pack(name):
    return os.path.join(PACK, name)


def home(name):
    return os.path.join(HOME, name)


def jload(path):
    return json.loads(read(path))


def yload(path):
    return yaml.safe_load(read(path))


def md_table(text, start_heading):
    """Rows of the first pipe table after a heading, as lists of cells."""
    i = text.find(start_heading)
    if i < 0:
        return []
    rows, started = [], False
    lines = text[i:].split("\n")
    if not start_heading.startswith("|"):
        lines = lines[1:]
    for line in lines:
        if line.startswith("|"):
            started = True
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                continue
            rows.append(cells)
        elif started:
            break
    return rows


def section(text, heading, level="## "):
    i = text.find(heading)
    if i < 0:
        return ""
    rest = text[i + len(heading):]
    j = rest.find("\n" + level)
    return rest if j < 0 else rest[:j]


def strip_md(s):
    s = re.sub(r"\*\*(.+?)\*\*", r"\1", s)
    s = re.sub(r"`([^`]*)`", r"\1", s)
    return s.strip()


data = {
    "_role": "explainer data",
    "_note": "Generated by build_data.py from the pack and the record. Never edit by hand: rebuild.",
}

# ---------------------------------------------------------------- brand context
bc = read(pack("brand-context.md"))
m = re.search(r"## File map.*?```json\n(.*?)\n```", bc, re.S)
file_map = json.loads(m.group(1)) if m else {}
data["file_map"] = file_map
roles = {k: v for k, v in file_map.items() if k not in ("brand", "brand_slug", "folder", "brand_domains", "prohibited_patterns", "type_ruling")}
data["roles"] = {
    "total": len(roles),
    "present": sorted(k for k, v in roles.items() if v),
    "null": sorted(k for k, v in roles.items() if v is None),
}
data["prohibited_patterns"] = file_map.get("prohibited_patterns", [])
gaps = []
rows = md_table(bc, "## Gaps and owners")
for r in rows[1:]:
    if len(r) >= 6:
        gaps.append({"item": strip_md(r[0]), "kind": r[1], "state": strip_md(r[2]), "owner": r[3], "step": strip_md(r[4]).strip("`"), "blocks": r[5]})
data["gaps"] = gaps
contr = []
for r in md_table(bc, "## Contradictions")[1:]:
    if len(r) >= 5:
        contr.append({"id": r[0], "what": r[1], "state": r[2], "owner": r[3]})
data["contradictions"] = contr
em = re.search(r"`hlr-studio-engine` (\d+\.\d+\.\d+)", bc)
engine_version = em.group(1) if em else None

# ---------------------------------------------------------------- tokens
read(pack("web/tokens.css"))  # the page's theme comes from this export (gen_theme.py); hashed for the stamp
tok = jload(pack("tokens.json"))


def walk(d, path=()):
    if isinstance(d, dict):
        if "$value" in d:
            yield path, d
        else:
            for k, v in d.items():
                if not k.startswith("$"):
                    yield from walk(v, path + (k,))


by_tag = {"documented": 0, "observed": 0, "derived": 0, "untagged": 0}
derived = []
all_tokens = [(p, d) for p, d in walk(tok) if p and p[0] != "contrast-pairs"]
for p, d in all_tokens:
    mt = re.match(r"\s*\[(documented|observed|derived)", d.get("$description", ""))
    tag = mt.group(1) if mt else "untagged"
    by_tag[tag] += 1
    if tag == "derived":
        derived.append(".".join(p))
modes = tok.get("$extensions", {}).get("com.hlr", {}).get("modes", {})
brand = []
for name, d in tok.get("color", {}).get("brand", {}).items():
    if isinstance(d, dict) and "$value" in d:
        mt = re.match(r"\s*\[(documented|observed|derived)[^\]]*\]\s*([^:.]*)", d.get("$description", ""))
        brand.append({"name": name, "hex": d["$value"], "tag": mt.group(1) if mt else None,
                      "source": (d.get("$extensions", {}).get("com.hlr", {}) or {}).get("source")})
pairs = tok.get("contrast-pairs", {}).get("pairs", [])
data["tokens"] = {
    "count": len(all_tokens), "by_tag": by_tag, "derived": derived,
    "grounds": modes.get("semantic", []), "canvases": modes.get("layout", []),
    "brand": brand, "pairs": len(pairs),
    "status": tok.get("$extensions", {}).get("com.hlr", {}).get("status"),
}

# theme values for the page: the light and night grounds of the semantic tokens
sem = tok.get("color", {}).get("semantic", {})


def resolve(v, seen=0):
    if isinstance(v, str) and v.startswith("{") and seen < 8:
        node = tok
        for k in v.strip("{}").split("."):
            node = node.get(k, {}) if isinstance(node, dict) else {}
        return resolve(node.get("$value"), seen + 1) if isinstance(node, dict) else None
    return v


theme = {}
for group, items in sem.items():
    if not isinstance(items, dict):
        continue
    for name, d in items.items():
        if isinstance(d, dict) and "$value" in d:
            key = f"{group}.{name}"
            ext = (d.get("$extensions", {}).get("com.hlr", {}) or {}).get("modes", {})
            theme[key] = {"light": resolve(d["$value"]), "night": resolve(ext.get("night", d["$value"])),
                          "deep": resolve(ext.get("deep", d["$value"])), "warm": resolve(ext.get("warm", d["$value"]))}
data["theme"] = theme

# ---------------------------------------------------------------- ledger
led = jload(pack("legal-ledger.json"))
counts = {}
entries = []
for e in led.get("entries", []):
    sev = e.get("severity") or e.get("status")
    counts[sev] = counts.get(sev, 0) + 1
    entries.append({"id": e.get("id"), "topic": e.get("topic"), "severity": sev, "title": e.get("title"),
                    "requires": e.get("requires") or e.get("rule")})
data["ledger"] = {"status": led.get("_status"), "version": led.get("version"), "signer": led.get("signer"),
                  "counts": counts, "entries": entries}

# ---------------------------------------------------------------- voice
vc = read(pack("voice-contract.md"))
quals = []
for block in re.split(r"^### ", section(vc, "## 3. The five qualities"), flags=re.M)[1:]:
    lines = [l.strip() for l in block.split("\n") if l.strip()]
    name = lines[0]
    check = next((l for l in lines if l.startswith("Check:")), None)
    defin = next((l for l in lines if l.startswith("Operational definition")), None)
    if defin:
        defin = re.sub(r"^Operational definition \[[^\]]*\]( \([^)]*\))?:\s*", "", defin)
    quals.append({"name": name, "definition": defin, "check": check[len("Check:"):].strip() if check else None})
rules_sec = section(vc, "## 4. Operating rules")
data["voice"] = {"qualities": quals, "rules": len(re.findall(r"^\d+\. ", rules_sec, re.M))}

ex = jload(pack("exemplars.json"))
by_ch = {}
for x in ex.get("exemplars", []):
    by_ch[x.get("channel")] = by_ch.get(x.get("channel"), 0) + 1
data["exemplars"] = {"count": len(ex.get("exemplars", [])), "by_channel": by_ch}

lex = jload(pack("concrete-lexicon.json"))
data["lexicon"] = {k: len(lex.get(k) or []) for k in ("product", "scene", "product_families", "product_names")}
data["lexicon"]["status"] = lex.get("_status")

# ---------------------------------------------------------------- products, types, routes
prod = jload(pack("products.json"))
items = {k: v for k, v in prod.items() if not k.startswith("_")}
kinds = {}
fams = set()
for v in items.values():
    kinds[v.get("kind")] = kinds.get(v.get("kind"), 0) + 1
    if v.get("family"):
        fams.add(v["family"])
empty_desc = sum(1 for v in items.values() if not (v.get("description") or "").strip())
data["products"] = {"count": len(items), "kinds": kinds, "families": len(fams), "empty_descriptions": empty_desc}

reg = jload(pack("type-registry-core.json"))
data["types"] = {
    "count": len(reg.get("types", {})),
    "status": reg.get("_status"),
    "items": [{"id": k, "label": v.get("label"), "status": v.get("status")} for k, v in reg.get("types", {}).items()],
}
ra = jload(pack("route-axes.json"))
data["route_axes"] = {"axes": ra.get("axes"), "default": ra.get("default_route_count"), "max": ra.get("max_route_count"),
                      "policy_empty": not ra.get("standing_angle_policy")}

# ---------------------------------------------------------------- library
fy = yload(pack("figma.yaml"))
sm = yload(pack("slotmap.yaml"))
mods, elems, nslots = [], [], 0
for mid, v in (sm.get("modules") or {}).items():
    slots = []
    for s in v.get("slots") or []:
        if isinstance(s, dict):
            slots.append({"id": s.get("id"), "role": s.get("role"), "typical": s.get("typical_chars"),
                          "max": s.get("max_chars"), "flex": s.get("flex_verified")})
    nslots += len(slots)
    row = {"id": mid, "name": v.get("name"), "use_when": v.get("use_when"), "slots": slots}
    (elems if mid.startswith("E") else mods).append(row)
fig = fy.get("figma", {})
data["library"] = {
    "file_name": fig.get("file_name"), "file_key": fig.get("file_key"), "pages": fig.get("pages"),
    "boards": fig.get("boards"), "templates": fy.get("templates"),
    "variables": len(fy.get("variable_ids") or {}), "text_styles": len(fy.get("text_style_ids") or {}),
    "modules": mods, "elements": elems, "slots": nslots,
    "measured_at": (sm.get("meta") or {}).get("measured_at"),
    "fonts_licensed": (fy.get("fonts") or {}).get("licensed"),
    "photos": len(fy.get("photos") or {}),
}

st = read(pack("strictness-map.md"))
srows = md_table(st, "| Element class")
data["strictness"] = [{"class": r[0], "binds": r[1], "modes": r[2], "floor": r[3], "content": r[4], "posture": r[5]}
                      for r in srows[1:] if len(r) >= 6]

# ---------------------------------------------------------------- process
rv = read(home("REVIEW.md"))
s4 = section(rv, "## 4. Risk tiers")
tiers = md_table(s4, "| Tier")
data["review_tiers"] = [{"tier": r[0], "what": strip_md(r[1]), "ships_on": strip_md(r[2]), "go": r[3]} for r in tiers[1:] if len(r) >= 4]
ns = re.search(r"^Never ships.*$", s4, re.M)
data["never_ships"] = ns.group(0) if ns else None
pr = re.search(r"^In production.*$", s4, re.M)
data["production_rule"] = pr.group(0) if pr else None

dec = read(home("DECISIONS.md"))
data["record"] = {"decision_lines": len(re.findall(r"^- ", dec, re.M)), "decision_dates": len(re.findall(r"^## \d{4}-\d{2}-\d{2}", dec, re.M))}
prog = read(home("PROGRESSION.md"))
steps = []
for blk in re.split(r"^## ", prog, flags=re.M)[1:]:
    title = blk.split("\n", 1)[0].strip()
    if title.startswith("Step") or title == "Process":
        steps.append({"step": title, "done": len(re.findall(r"^\s*- \[x\]", blk, re.M)), "open": len(re.findall(r"^\s*- \[ \]", blk, re.M))})
data["progress"] = steps

# ---------------------------------------------------------------- the demo run
demo = {}
bm = read(home(f"{DEMO}/brief-made-to-order-pendants.md"))
secs = []
for blk in re.split(r"^## ", bm, flags=re.M)[1:]:
    head, _, body = blk.partition("\n")
    secs.append({"heading": head.strip(), "text": strip_md(body)})
demo["brief"] = {"title": bm.split("\n", 1)[0].lstrip("# ").strip(), "sections": secs}

im = read(home(f"{DEMO}/{SLUG}.intake.md"))
vm = re.search(r"Verdict: \*\*(\w[\w-]*)\*\*", im)
gaps_by = {}
for blk in re.split(r"^\*\*(\w+)\*\*\s*$", section(im, "## Gaps by owner"), flags=re.M)[1:]:
    pass
cur = None
for line in section(im, "## Gaps by owner").split("\n"):
    h = re.match(r"^\*\*(\w+)\*\*\s*$", line.strip())
    if h:
        cur = h.group(1)
        gaps_by[cur] = []
    elif line.startswith("- ") and cur:
        gaps_by[cur].append(line[2:].strip())
rec = re.search(r"^Recommended: (.*)$", im, re.M)
demo["intake"] = {"verdict": vm.group(1) if vm else None, "gaps": gaps_by, "recommended": rec.group(1) if rec else None}
run1 = home(f"{DEMO}/{SLUG}.intake.run1-fail.md")
if os.path.exists(run1):
    r1 = read(run1)
    vm1 = re.search(r"Verdict: \*\*(\w[\w-]*)\*\*", r1)
    er = re.search(r"^- ERROR (.*)$", r1, re.M)
    demo["intake_first_run"] = {"verdict": vm1.group(1) if vm1 else None, "error": er.group(1) if er else None}

rt = jload(home(f"{DEMO}/{SLUG}.routes.json"))
demo["routes"] = [{"id": r.get("id"), "axis": r.get("axis"), "angle": r.get("angle"), "tension": r.get("tension"),
                   "weakness": r.get("weakness")} for r in rt.get("routes", [])]
demo["recommended"] = rt.get("recommended")
demo["recommended_why"] = rt.get("recommended_why")
demo["provisional"] = rt.get("provisional")

lints = {}
for key, fn in (("brief", "brief-lint"), ("copy", "copy_lint"), ("fit", "fit_check"), ("voice", "voice-lint")):
    j = jload(home(f"{DEMO}/{SLUG}.{fn}.json"))
    lints[key] = {"verdict": j.get("verdict"), "errors": len(j.get("errors") or []),
                  "warns": len(j.get("warns") or [])}
    if key == "fit":
        lints[key]["cuts_checked"] = (j.get("checked") or {}).get("cuts_checked")
    if key == "voice":
        lints[key]["advisory"] = j.get("advisory")
demo["lints"] = lints

fd = read(home(f"{DEMO}/{SLUG}.findings.md"))
sm_ = re.search(r"^(\d+ findings, routed by who can act on them\..*)$", fd, re.M)
groups = []
for blk in re.split(r"^## ", fd, flags=re.M)[1:]:
    head, _, body = blk.partition("\n")
    owner, _, subtitle = head.partition(EM_DASH)
    groups.append({"owner": owner.strip(), "subtitle": subtitle.strip(),
                   "items": [l[2:].strip() for l in body.split("\n") if l.startswith("- ")]})
demo["findings"] = {"summary": sm_.group(1) if sm_ else None, "groups": groups}

bd = read(home(f"{DEMO}/build.md"))
copy_rows = md_table(bd, "## Copy")
demo["copy"] = [{"slot": strip_md(r[0]), "copy": r[1], "accent": r[2]} for r in copy_rows[1:] if len(r) >= 3]
sp = re.search(r"^Subject: (.*?)\. Preheader: (.*)$", bd, re.M)
demo["subject"] = sp.group(1) + "." if sp else None
demo["preheader"] = sp.group(2) if sp else None
slice_rows = md_table(bd, "## Slices and alt text")
demo["slices"] = [{"slice": r[0], "alt": r[1]} for r in slice_rows[1:] if len(r) >= 2]
where = section(bd, "## Where it is")
demo["where"] = [strip_md(l[2:]) for l in where.split("\n") if l.startswith("- ")]
data["demo"] = demo

# ---------------------------------------------------------------- stamp
commit = args.commit
if not commit:
    try:
        commit = subprocess.run(["git", "-C", HOME, "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        commit = None
dirty = None
try:
    out = subprocess.run(["git", "-C", HOME, "status", "--porcelain", "--", PACK_REL], capture_output=True, text=True, check=True).stdout
    dirty = bool(out.strip())
except Exception:
    pass
data["stamp"] = {
    "built_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "brand_home_commit": commit, "pack_uncommitted_changes": dirty,
    "engine": f"hlr-studio-engine {engine_version}" if engine_version else None,
    "pack": PACK_REL, "sources": dict(sorted(used.items())),
}

text = json.dumps(data, ensure_ascii=False, indent=1)
if EM_DASH in text:
    hits = [m.start() for m in re.finditer(EM_DASH, text)][:3]
    sys.exit("build_data.py: an em dash reached the data; first at " + ", ".join(repr(text[max(0, h - 60):h + 20]) for h in hits))
with open(args.out, "w", encoding="utf-8") as f:
    f.write(text + "\n")
print(f"wrote {args.out}: {len(used)} sources, {len(text)} bytes, commit {commit}")
